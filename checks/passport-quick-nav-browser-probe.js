(()=>{
window.addEventListener('load',async()=>{
 const target=document.getElementById('mpq-test-result');
 const wait=ms=>new Promise(done=>setTimeout(done,ms));
 const ok=(value,msg)=>{if(!value)throw Error(msg);};
 try{
  for(let i=0;i<150&&!window.MicroportQuickNav?.getState().ready;i++)await wait(40);
  const api=window.MicroportQuickNav,state=api?.getState();
  ok(state?.ready,'quick navigation not loaded');
  ok(state.actions===10,'ten shortcuts not registered');
  ok(api.getCountryURL().includes('country='),'project country handoff missing');
  const root=document.getElementById('mpq-navigation');
  ok(root?.tagName==='DETAILS','quick navigation is not a collapsible panel');
  ok(!root.open,'quick navigation must begin closed');
  root.open=true;
  const controls=[...root.querySelectorAll('[data-mpq-action]')];
  ok(controls.length===10,'ten working shortcut controls missing');
  ok(controls.every(x=>x.getAttribute('aria-label')),'shortcut labels inaccessible');
  const expected=['overview','facts','related','citation','inspector','comparison','geography','review','saved','country'];
  ok(JSON.stringify(controls.map(x=>x.dataset.mpqAction))===JSON.stringify(expected),'shortcut order changed');
  if(new URLSearchParams(location.search).has('snapshot')){
   window.scrollTo(0,0);
   target.textContent='PASS: ten compact source navigation actions captured';
   return;
  }
  document.getElementById('mpq-preview-style')?.remove();
  for(let i=0;i<100&&!window.MicroportReading?.getState().ready;i++)await wait(30);
  const reader=window.MicroportReading;
  ok(reader?.getState().ready,'reading controls unavailable for focus integration');
  reader.activate('focus');
  await api.activate('inspector');
  ok(!reader.getState().focused,'shortcut left its destination hidden by focus mode');
  const inspector=document.getElementById('mpf-inspector');
  ok(getComputedStyle(inspector).display!=='none','inspector remains hidden');
  ok(document.activeElement===inspector,'keyboard focus did not reach inspector');
  ok(document.getElementById('mpf-inspector')?.open,'field inspector not opened by quick navigation');
  await api.activate('comparison');
  ok(document.getElementById('mpd-compare')?.open,'evidence comparison not opened by quick navigation');
  await api.activate('geography');
  ok(document.getElementById('mpl-location')?.open,'geographic context not opened by quick navigation');
  await api.activate('overview');
  ok(root.querySelector('#mpq-status').textContent.includes('overview'),'overview feedback missing');
  ok(document.activeElement===document.querySelector('main .hero'),'overview focus missing');
  reader.activate('focus');
  await api.activate('facts');
  ok(reader.getState().focused,'original facts shortcut unexpectedly exited focus mode');
  reader.activate('tools');
  const originalParent=inspector.parentNode,next=inspector.nextSibling;
  inspector.remove();
  const stale=api.activate('inspector');
  await api.activate('overview');
  originalParent.insertBefore(inspector,next);
  ok(await stale===false,'older delayed shortcut overrode a newer request');
  ok(document.activeElement===document.querySelector('main .hero'),'stale shortcut stole focus');
  inspector.remove();
  const late=api.activate('inspector');
  setTimeout(()=>originalParent.insertBefore(inspector,next),120);
  ok(await late===true,'late-loaded destination did not recover');
  ok(document.activeElement===inspector,'late-loaded destination focus missing');
  const outer=document.createElement('details'),inner=document.createElement('details');
  const summary=document.createElement('summary');summary.textContent='Temporary nested navigation fixture';
  outer.append(summary,inner);inner.append(inspector);originalParent.insertBefore(outer,next);
  await api.activate('inspector');
  ok(outer.open&&inner.open&&inspector.open,'nested disclosure ancestors stayed closed');
  ok(document.activeElement===inspector,'nested destination not focused');
  originalParent.insertBefore(inspector,next);outer.remove();
  target.textContent='PASS: quick navigation focus-mode integration, keyboard focus, nested disclosures, latest-request wins and delayed destination recovery';
 }catch(e){target.textContent='FAIL: '+e.message;}
});
})();